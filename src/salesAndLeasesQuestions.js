// Course scope comes from the finished outline; context records point to the
// local class materials. Public links identify the controlling rule text.
const UCC = "https://www.law.cornell.edu/ucc/";
const USC = "https://www.law.cornell.edu/uscode/text/15/";
const CISG = "https://uncitral.un.org/en/texts/salegoods/conventions/sale_of_goods/cisg";
const FL_SCOPE = "https://www.flsenate.gov/Laws/Statutes/2025/672.102";

function source(rule) {
  if (rule === "CISG") return { sourceUrl: CISG, sourceLabel: "CISG · Articles 1–3, 6 and 10" };
  if (rule === "FL-672.102") return { sourceUrl: FL_SCOPE, sourceLabel: "Florida Statutes § 672.102" };
  if (rule.startsWith("15-")) return { sourceUrl: USC + rule.slice(3), sourceLabel: `15 U.S.C. § ${rule.slice(3)}` };
  return { sourceUrl: UCC + rule.split("-")[0] + "/" + rule, sourceLabel: `UCC § ${rule}` };
}

// Row keys stay stable when wording or ordering changes. Short aliases preserve
// the tested distinction; the indicator supplies the rest of the question.
const a = (key, indicator, answer, ...acceptedAnswers) => ({ key, indicator, answer, acceptedAnswers });
const c = (key, title, ...answers) => ({ key, title, answers });

function grid(id, title, section, rule, columns, context = "", prompt = "Use each clue to recall the rule, requirement, or legal consequence.") {
  const prefix = `sales-${id}`;
  return {
    id: prefix, type: "sporcle-grid", clueLayout: "above", title, prompt, ...source(rule),
    courseSources: [`Finished Sales and Leases Outline · ${section}`, ...(context ? [context] : [])],
    columns: columns.map(({ key, title: columnTitle, answers }) => ({
      id: `${prefix}-${key}`, title: columnTitle,
      answers: answers.map(({ key: rowKey, ...row }) => ({ id: `${prefix}-${rowKey}`, ...row })),
    })),
  };
}

