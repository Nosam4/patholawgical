function flow(id, title, section, rule, prompt, definitions, links, context) {
  const prefix = `sales-${id}`;
  const nodes = definitions.map(([key, x, y, text, clue, kind = "decision", aliases = []]) => ({
    id: `${prefix}-${key}`, x, y, width: 280, height: 100, kind,
    ...(clue === null ? { label: text, quiz: false } : { answer: text, clue, acceptedAnswers: aliases }),
  }));
  const layout = readableFlowchartLayout(nodes);
  return {
    id: prefix, type: "flowchart", avoidNodes: true, title, prompt, ...source(rule),
    courseSources: [`Finished Sales and Leases Outline · ${section}`, context],
    width: 1040, height: layout.height, nodes: layout.nodes,
    arrows: links.map(([from, to, label, rightGutter]) => {
      const fromId = `${prefix}-${from}`;
      const toId = `${prefix}-${to}`;
      const start = layout.nodes.find((node) => node.id === fromId);
      const end = layout.nodes.find((node) => node.id === toId);
      return {
        from: fromId, to: toId, label,
        fromAnchor: rightGutter ? "right" : "bottom",
        toAnchor: rightGutter ? "right" : "top",
        ...(rightGutter ? {
          waypoints: [{ x: rightGutter, y: start.y + start.height / 2 }, { x: rightGutter, y: end.y + end.height / 2 }],
          labelPosition: { x: rightGutter, y: (start.y + start.height + end.y) / 2 },
        } : {}),
      };
    }),
  };
}

